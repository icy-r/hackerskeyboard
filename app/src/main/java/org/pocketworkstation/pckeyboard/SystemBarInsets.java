package org.pocketworkstation.pckeyboard;

import android.app.Activity;
import android.view.View;

import androidx.core.graphics.Insets;
import androidx.core.view.ViewCompat;
import androidx.core.view.WindowInsetsCompat;

/**
 * Android 15+ draws activities edge-to-edge. Pads an activity's content by whatever
 * system bar and display cutout insets reach it, so nothing ends up under the status
 * bar or navigation bar. (When an action bar already handles the top inset, the
 * content view only receives the remaining insets.)
 */
final class SystemBarInsets {
    private SystemBarInsets() {}

    static void apply(Activity activity) {
        View content = activity.findViewById(android.R.id.content);
        if (content == null) return;
        ViewCompat.setOnApplyWindowInsetsListener(content, (v, insets) -> {
            Insets bars = insets.getInsets(WindowInsetsCompat.Type.systemBars()
                    | WindowInsetsCompat.Type.displayCutout());
            v.setPadding(bars.left, bars.top, bars.right, bars.bottom);
            return insets;
        });
        ViewCompat.requestApplyInsets(content);
    }
}
